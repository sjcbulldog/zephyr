"""Generate a C file defining the infsingle_blob_{fw,nvram,clm} arrays."""

import argparse


def nvram_image(path):
    """Turn NVRAM text into NUL-separated entries, padded to 4 bytes.

    The device expects "key=value" entries each terminated by NUL, the list
    terminated by an extra NUL, and a total size that is a multiple of 4
    (the boot code writes a length token derived from that size).
    """
    out = bytearray()
    with open(path, "rb") as f:
        for line in f.read().replace(b"\r", b"").split(b"\n"):
            line = line.strip()
            if not line or line.startswith(b"#"):
                continue
            out += line + b"\0"
    out += b"\0"
    while len(out) % 4:
        out += b"\0"
    return bytes(out)


def emit(out, name, data):
    # Symbol names match the extern declarations in infsingle_fw.c.
    out.write(f"const uint8_t infsingle_blob_{name}[] = {{\n")
    for i in range(0, len(data), 16):
        out.write("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
    out.write("};\n")
    out.write(f"const uint32_t infsingle_blob_{name}_len = {len(data)};\n\n")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--fw", required=True)
    p.add_argument("--clm", required=True)
    p.add_argument("--nvram", required=True)
    p.add_argument("--out", required=True)
    a = p.parse_args()

    with open(a.fw, "rb") as f:
        fw = f.read()
    with open(a.clm, "rb") as f:
        clm = f.read()

    with open(a.out, "w", newline="\n") as out:
        out.write("/* Generated by gen_blob.py. Do not edit. */\n#include <stdint.h>\n\n")
        emit(out, "fw", fw)
        emit(out, "nvram", nvram_image(a.nvram))
        emit(out, "clm", clm)


if __name__ == "__main__":
    main()
